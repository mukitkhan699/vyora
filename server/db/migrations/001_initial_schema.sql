CREATE TABLE zunari_users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id TEXT NOT NULL UNIQUE,
  username TEXT NOT NULL,
  name TEXT NOT NULL,
  email TEXT,
  password_hash TEXT,
  email_verified BOOLEAN NOT NULL DEFAULT TRUE,
  created_at BIGINT NOT NULL,
  joined_date TEXT,
  avatar_url TEXT NOT NULL DEFAULT '',
  banner_url TEXT,
  bio TEXT,
  location TEXT,
  website TEXT,
  verified BOOLEAN NOT NULL DEFAULT FALSE,
  is_gold BOOLEAN NOT NULL DEFAULT FALSE,
  followers_count INTEGER NOT NULL DEFAULT 0 CHECK (followers_count >= 0),
  following_count INTEGER NOT NULL DEFAULT 0 CHECK (following_count >= 0)
);

CREATE UNIQUE INDEX zunari_users_username_ci ON zunari_users (lower(username));
CREATE UNIQUE INDEX zunari_users_email_ci ON zunari_users (lower(email)) WHERE email IS NOT NULL;

CREATE TABLE zunari_sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER REFERENCES zunari_users(id) ON DELETE CASCADE,
  csrf_token TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE INDEX zunari_sessions_user_id_idx ON zunari_sessions(user_id);
CREATE INDEX zunari_sessions_expires_at_idx ON zunari_sessions(expires_at);

CREATE TABLE zunari_password_resets (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES zunari_users(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  used_at BIGINT
);

CREATE TABLE zunari_posts (
  id TEXT PRIMARY KEY,
  author_id TEXT NOT NULL REFERENCES zunari_users(public_id) ON DELETE CASCADE,
  content TEXT NOT NULL,
  media_urls TEXT[] NOT NULL DEFAULT '{}',
  reply_to_post_id TEXT REFERENCES zunari_posts(id) ON DELETE SET NULL,
  quote_post_id TEXT REFERENCES zunari_posts(id) ON DELETE SET NULL,
  created_at BIGINT NOT NULL,
  likes_count INTEGER NOT NULL DEFAULT 0 CHECK (likes_count >= 0),
  reposts_count INTEGER NOT NULL DEFAULT 0 CHECK (reposts_count >= 0),
  replies_count INTEGER NOT NULL DEFAULT 0 CHECK (replies_count >= 0),
  views_count INTEGER NOT NULL DEFAULT 0 CHECK (views_count >= 0)
);
CREATE INDEX zunari_posts_author_created_idx ON zunari_posts(author_id, created_at DESC);
CREATE INDEX zunari_posts_feed_idx ON zunari_posts(created_at DESC);
CREATE INDEX zunari_posts_reply_idx ON zunari_posts(reply_to_post_id, created_at);

CREATE TABLE zunari_follows (
  follower_id TEXT NOT NULL REFERENCES zunari_users(public_id) ON DELETE CASCADE,
  following_id TEXT NOT NULL REFERENCES zunari_users(public_id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (follower_id, following_id),
  CHECK (follower_id <> following_id)
);
CREATE INDEX zunari_follows_following_idx ON zunari_follows(following_id);

CREATE TABLE zunari_likes (
  user_id TEXT NOT NULL REFERENCES zunari_users(public_id) ON DELETE CASCADE,
  post_id TEXT NOT NULL REFERENCES zunari_posts(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (user_id, post_id)
);
CREATE TABLE zunari_reposts (
  user_id TEXT NOT NULL REFERENCES zunari_users(public_id) ON DELETE CASCADE,
  post_id TEXT NOT NULL REFERENCES zunari_posts(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (user_id, post_id)
);
CREATE TABLE zunari_bookmarks (
  user_id TEXT NOT NULL REFERENCES zunari_users(public_id) ON DELETE CASCADE,
  post_id TEXT NOT NULL REFERENCES zunari_posts(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (user_id, post_id)
);

CREATE TABLE zunari_polls (
  id TEXT PRIMARY KEY,
  post_id TEXT NOT NULL UNIQUE REFERENCES zunari_posts(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);
CREATE TABLE zunari_poll_options (
  poll_id TEXT NOT NULL REFERENCES zunari_polls(id) ON DELETE CASCADE,
  option_index SMALLINT NOT NULL CHECK (option_index >= 0),
  text TEXT NOT NULL,
  seed_vote_count BIGINT NOT NULL DEFAULT 0 CHECK (seed_vote_count >= 0),
  PRIMARY KEY (poll_id, option_index)
);
CREATE TABLE zunari_poll_votes (
  poll_id TEXT NOT NULL,
  option_index SMALLINT NOT NULL,
  user_id TEXT NOT NULL REFERENCES zunari_users(public_id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (poll_id, user_id),
  FOREIGN KEY (poll_id, option_index)
    REFERENCES zunari_poll_options(poll_id, option_index) ON DELETE CASCADE
);

CREATE TABLE zunari_notifications (
  id TEXT PRIMARY KEY,
  recipient_id TEXT NOT NULL REFERENCES zunari_users(public_id) ON DELETE CASCADE,
  sender_id TEXT NOT NULL REFERENCES zunari_users(public_id) ON DELETE CASCADE,
  type TEXT NOT NULL CHECK (type IN ('like', 'repost', 'reply', 'follow', 'mention')),
  post_id TEXT REFERENCES zunari_posts(id) ON DELETE SET NULL,
  post_content TEXT,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  created_at BIGINT NOT NULL
);
CREATE INDEX zunari_notifications_recipient_idx
  ON zunari_notifications(recipient_id, created_at DESC);

CREATE TABLE zunari_conversations (
  id TEXT PRIMARY KEY,
  participant_a_id TEXT NOT NULL REFERENCES zunari_users(public_id) ON DELETE CASCADE,
  participant_b_id TEXT NOT NULL REFERENCES zunari_users(public_id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  CHECK (participant_a_id COLLATE "C" < participant_b_id COLLATE "C"),
  UNIQUE (participant_a_id, participant_b_id)
);
CREATE TABLE zunari_messages (
  id TEXT PRIMARY KEY,
  conversation_id TEXT NOT NULL REFERENCES zunari_conversations(id) ON DELETE CASCADE,
  sender_id TEXT NOT NULL REFERENCES zunari_users(public_id) ON DELETE CASCADE,
  recipient_id TEXT NOT NULL REFERENCES zunari_users(public_id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  CHECK (sender_id <> recipient_id)
);
CREATE INDEX zunari_messages_conversation_idx
  ON zunari_messages(conversation_id, created_at);

CREATE TABLE zunari_media_assets (
  id TEXT PRIMARY KEY,
  owner_id TEXT NOT NULL REFERENCES zunari_users(public_id) ON DELETE CASCADE,
  object_key TEXT NOT NULL UNIQUE,
  filename TEXT NOT NULL,
  mime_type TEXT NOT NULL,
  byte_size BIGINT NOT NULL CHECK (byte_size > 0),
  purpose TEXT NOT NULL CHECK (purpose IN ('profile-avatar', 'profile-cover', 'post-image')),
  status TEXT NOT NULL CHECK (status IN ('pending', 'ready', 'deleting')),
  visibility TEXT NOT NULL DEFAULT 'private' CHECK (visibility IN ('private', 'public')),
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  upload_expires_at BIGINT NOT NULL
);
CREATE INDEX zunari_media_owner_idx ON zunari_media_assets(owner_id, created_at DESC);
CREATE INDEX zunari_media_cleanup_idx ON zunari_media_assets(status, expires_at);

CREATE TABLE zunari_upload_rate_limits (
  user_id TEXT NOT NULL REFERENCES zunari_users(public_id) ON DELETE CASCADE,
  window_start BIGINT NOT NULL,
  request_count INTEGER NOT NULL CHECK (request_count > 0),
  PRIMARY KEY (user_id, window_start)
);
